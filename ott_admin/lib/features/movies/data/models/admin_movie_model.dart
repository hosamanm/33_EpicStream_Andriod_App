import 'package:cloud_firestore/cloud_firestore.dart';
import '../../domain/entities/admin_movie_entity.dart';

class AdminMovieModel extends AdminMovieEntity {
  const AdminMovieModel({
    required super.id,
    required super.title,
    super.originalTitle,
    required super.description,
    required super.shortDescription,
    required super.posterUrl,
    required super.bannerUrl,
    super.logoUrl,
    super.thumbnailUrl,
    super.trailerVideoId,
    super.trailerPlaybackUrl,
    super.movieVideoId,
    super.moviePlaybackUrl,
    super.subtitleUrls = const [],
    super.audioTracks = const [],
    required super.genreIds,
    super.genreNames = const [],
    required super.categoryIds,
    required super.language,
    required super.country,
    super.cast = const [],
    super.crew = const [],
    required super.director,
    required super.producer,
    required super.writer,
    required super.musicDirector,
    required super.duration,
    required super.releaseDate,
    super.releaseYear = 0,
    required super.ageRating,
    required super.imdbRating,
    super.status = AdminMovieStatus.draft,
    super.isFeatured = false,
    super.isTrending = false,
    super.isEditorsChoice = false,
    required super.createdAt,
    required super.updatedAt,
  });

  factory AdminMovieModel.fromFirestore(DocumentSnapshot doc) {
    final data = doc.data() as Map<String, dynamic>;
    return AdminMovieModel(
      id: doc.id,
      title: data['title'] ?? '',
      originalTitle: data['originalTitle'],
      description: data['description'] ?? '',
      shortDescription: data['shortDescription'] ?? '',
      posterUrl: data['posterUrl'] ?? '',
      bannerUrl: data['bannerUrl'] ?? '',
      logoUrl: data['logoUrl'],
      thumbnailUrl: data['thumbnailUrl'],
      trailerVideoId: data['trailerVideoId'],
      trailerPlaybackUrl: data['trailerPlaybackUrl'],
      movieVideoId: data['movieVideoId'],
      moviePlaybackUrl: data['moviePlaybackUrl'],
      subtitleUrls: List<String>.from(data['subtitleUrls'] ?? []),
      audioTracks: (data['audioTracks'] as List?)?.map((e) => Map<String, String>.from(e)).toList() ?? [],
      genreIds: List<String>.from(data['genreIds'] ?? []),
      genreNames: List<String>.from(data['genreNames'] ?? []),
      categoryIds: List<String>.from(data['categoryIds'] ?? []),
      language: data['language'] ?? 'en',
      country: data['country'] ?? '',
      cast: (data['cast'] as List?)?.map((e) => Map<String, String>.from(e)).toList() ?? [],
      crew: (data['crew'] as List?)?.map((e) => Map<String, String>.from(e)).toList() ?? [],
      director: data['director'] ?? '',
      producer: data['producer'] ?? '',
      writer: data['writer'] ?? '',
      musicDirector: data['musicDirector'] ?? '',
      duration: data['duration'] ?? 0,
      releaseDate: data['releaseDate'] ?? '',
      releaseYear: data['releaseYear'] ?? 0,
      ageRating: data['ageRating'] ?? '',
      imdbRating: (data['imdbRating'] as num?)?.toDouble() ?? 0.0,
      status: AdminMovieStatus.values.firstWhere(
        (e) => e.name == (data['status'] ?? 'draft'),
        orElse: () => AdminMovieStatus.draft,
      ),
      isFeatured: data['isFeatured'] ?? false,
      isTrending: data['isTrending'] ?? false,
      isEditorsChoice: data['isEditorsChoice'] ?? false,
      createdAt: (data['createdAt'] as Timestamp?)?.toDate() ?? DateTime.now(),
      updatedAt: (data['updatedAt'] as Timestamp?)?.toDate() ?? DateTime.now(),
    );
  }

  Map<String, dynamic> toFirestore() {
    return {
      'title': title,
      'originalTitle': originalTitle,
      'description': description,
      'shortDescription': shortDescription,
      'posterUrl': posterUrl,
      'bannerUrl': bannerUrl,
      'logoUrl': logoUrl,
      'thumbnailUrl': thumbnailUrl,
      'trailerVideoId': trailerVideoId,
      'trailerPlaybackUrl': trailerPlaybackUrl,
      'movieVideoId': movieVideoId,
      'moviePlaybackUrl': moviePlaybackUrl,
      'subtitleUrls': subtitleUrls,
      'audioTracks': audioTracks,
      'genreIds': genreIds,
      'genreNames': genreNames,
      'categoryIds': categoryIds,
      'language': language,
      'country': country,
      'cast': cast,
      'crew': crew,
      'director': director,
      'producer': producer,
      'writer': writer,
      'musicDirector': musicDirector,
      'duration': duration,
      'releaseDate': releaseDate,
      'releaseYear': releaseYear,
      'ageRating': ageRating,
      'imdbRating': imdbRating,
      'status': status.name,
      'isFeatured': isFeatured,
      'isTrending': isTrending,
      'isEditorsChoice': isEditorsChoice,
      'createdAt': Timestamp.fromDate(createdAt),
      'updatedAt': Timestamp.fromDate(updatedAt),
    };
  }
}
